import { writeFile, mkdir } from "node:fs/promises";

const SOURCE_URL = "https://raw.githubusercontent.com/chengyang1017/flutter-languages-config/main/lib/src/languages.dart";
const SOURCE_REPO = "chengyang1017/flutter-languages-config";

const response = await fetch(SOURCE_URL, { headers: { "User-Agent": "elyra-language-sync" } });
if (!response.ok) throw new Error(`Language config download failed: ${response.status} ${response.statusText}`);
const dart = await response.text();

const entries = [];
const blockPattern = /LanguageConfig\(\s*code:\s*'([^']+)'\s*,\s*flag:\s*'([^']*)'\s*,\s*names:\s*\{([\s\S]*?)\}\s*,\s*sortKeys:/g;
for (const match of dart.matchAll(blockPattern)) {
  const [, sourceCode, flag, namesBlock] = match;
  const names = {};
  for (const nameMatch of namesBlock.matchAll(/'([^']+)'\s*:\s*'([^']*)'/g)) names[nameMatch[1]] = nameMatch[2];
  if (!names.en && !names.zh && !names.ms) continue;
  entries.push({
    code: sourceCode === "zh" ? "zh-CN" : sourceCode,
    sourceCode,
    flag,
    names,
  });
}

if (entries.length < 20) throw new Error(`Parsed only ${entries.length} languages; refusing to overwrite the generated catalog.`);

const generatedAt = new Date().toISOString();
const body = `// AUTO-GENERATED by scripts/sync-language-config.mjs. Do not edit manually.\n` +
`// Source: ${SOURCE_REPO} / lib/src/languages.dart\n` +
`export type ElyraLanguageCatalogEntry = { code: string; sourceCode: string; flag: string; names: Record<string,string> };\n` +
`export const LANGUAGE_CATALOG_SOURCE = ${JSON.stringify(SOURCE_REPO)} as const;\n` +
`export const LANGUAGE_CATALOG_GENERATED_AT = ${JSON.stringify(generatedAt)} as const;\n` +
`export const ELYRA_LANGUAGE_CATALOG: ElyraLanguageCatalogEntry[] = ${JSON.stringify(entries, null, 2)};\n` +
`export function languageName(entry: ElyraLanguageCatalogEntry, uiLocale: string): string {\n` +
`  const base = uiLocale.toLowerCase().split(/[-_]/)[0];\n` +
`  return entry.names[base] ?? entry.names.en ?? entry.names.zh ?? entry.code;\n` +
`}\n`;

for (const path of ["apps/admin/lib/language-catalog.generated.ts", "apps/web/lib/language-catalog.generated.ts"]) {
  await mkdir(path.slice(0, path.lastIndexOf("/")), { recursive: true });
  await writeFile(path, body, "utf8");
}
console.log(`Synced ${entries.length} languages from ${SOURCE_REPO}.`);
